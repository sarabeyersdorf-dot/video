/* ============================================================================
   Goldframe AI — disclosure & compliance
   ----------------------------------------------------------------------------
   This is the part that keeps an agent out of trouble, and it is not optional
   décor — it is the reason a brokerage can let its people use AI at all.

   THE LAW, SHORT VERSION
   California AB 723 took effect on 1 January 2026. If a listing image is altered
   to ADD, REMOVE or CHANGE a physical element — furniture, fixtures, paint,
   flooring, landscaping, the view, the sky — then the marketing must say so
   clearly AND must tell people how to see the untouched original. That applies
   to the MLS, your website, social media and print.

   Brightness, contrast, white balance, cropping and straightening are explicitly
   NOT covered. They are enhancement, not alteration. Goldframe encodes that line
   directly: grading and reframing are silent; staging, decluttering, sky swaps
   and added people always disclose.

   Most MLSs want more than the law: CRMLS wants a watermark AND a note in the
   remarks; Bright wants "Virtually Staged" in the caption; MRED and NWMLS want a
   watermark. NAR handles it under Article 12 (present a true picture) with no
   prescribed wording. So Goldframe does the strictest sensible thing everywhere:
   burn the label into the picture, write the remarks line, and keep the original.

   Burning the label into the PHOTO rather than overlaying it on the video is a
   deliberate choice — it means the disclosure survives every crop, re-export,
   screenshot and repost, and it needs no cooperation from the video renderer.

   None of this is legal advice, and rules differ by MLS and state. It is a
   sensible, documented default that an agent can point to.
   ========================================================================== */
(function () {
  "use strict";

  var LS_LOG = "gf_ai_disclosures";

  // Which edits change the property, and which merely make the photo look right.
  var ALTERATIONS = {
    stage:     { label: "VIRTUALLY STAGED",  why: "Furniture and decor were added digitally." },
    restage:   { label: "VIRTUALLY STAGED",  why: "Furniture was digitally replaced." },
    declutter: { label: "DIGITALLY ALTERED", why: "Existing items were digitally removed." },
    sky:       { label: "DIGITALLY ALTERED", why: "The sky was digitally replaced." },
    people:    { label: "DIGITALLY ALTERED", why: "People were digitally added for illustration." },
    generic:   { label: "DIGITALLY ALTERED", why: "The image was digitally altered." },
    motion:    { label: "AI-GENERATED MOTION", why: "Camera movement in this clip was generated by AI from a still photo." }
  };
  var ENHANCEMENTS = { grade: 1, reframe: 1, crop: 1, parallax: 1 };

  function isAlteration(job) { return !ENHANCEMENTS[job]; }
  function labelFor(job) { return (ALTERATIONS[job] || ALTERATIONS.generic).label; }

  /* ------------------------------------------------------------- watermarking
     Bottom-left, semi-transparent, sized to the image so it reads the same on a
     phone thumbnail and a 4K screen. Drawn twice — dark shadow under light text
     — so it stays legible over both a white kitchen and a dark sofa. */
  function watermark(canvas, job) {
    var text = labelFor(job);
    var g = canvas.getContext("2d");
    var W = canvas.width, H = canvas.height;
    var size = Math.max(11, Math.round(Math.min(W, H) * 0.026));
    var pad = Math.round(size * 0.75);

    g.save();
    g.font = "600 " + size + "px system-ui, -apple-system, 'Segoe UI', Roboto, Arial, sans-serif";
    g.textBaseline = "alphabetic";
    var w = g.measureText(text).width;
    var boxH = size + pad;
    var x = pad, y = H - pad;

    g.globalAlpha = 0.42;
    g.fillStyle = "#000";
    g.fillRect(x - pad * 0.6, y - boxH + pad * 0.25, w + pad * 1.2, boxH * 0.92);
    g.globalAlpha = 0.95;
    g.fillStyle = "#fff";
    g.fillText(text, x, y - pad * 0.35);
    g.restore();
    return canvas;
  }

  /* --------------------------------------------------------------- the record
     Every altered image gets a row: what was done, by which model, with which
     instruction, when, and the name of the original file that was kept. This is
     the thing you hand to a broker or an MLS if anyone ever asks. */
  function log(entry) {
    var rows = read();
    rows.unshift({
      at: new Date().toISOString(),
      photo: entry.photo || "",
      job: entry.job,
      label: labelFor(entry.job),
      model: entry.model || "on-device",
      prompt: (entry.prompt || "").slice(0, 400),
      address: entry.address || "",
      disclosed: isAlteration(entry.job)
    });
    try { localStorage.setItem(LS_LOG, JSON.stringify(rows.slice(0, 500))); } catch (e) {}
    return rows[0];
  }
  function read() {
    try { return JSON.parse(localStorage.getItem(LS_LOG) || "[]"); } catch (e) { return []; }
  }
  function clear() { try { localStorage.removeItem(LS_LOG); } catch (e) {} }

  /* -------------------------------------------------------- the wording to use */
  function remarksLine(url) {
    var s = "Some images have been digitally altered and/or virtually staged for illustrative purposes and do not depict the property's actual condition.";
    if (url) s += " Unaltered original photos: " + url;
    return s;
  }
  function socialLine() {
    return "Some images digitally altered / virtually staged. Not a depiction of actual condition.";
  }

  // What kind of alteration is this clip carrying, if any?
  //
  // Read `labelJob`, NOT `job`. `job` is only the most recent thing done, so a
  // staged room that was later polished would report "grade" and quietly drop
  // out of the disclosure — while still carrying VIRTUALLY STAGED in its
  // pixels. `labelJob` is the sticky one: it is set when a photo is first
  // altered and survives every later enhancement.
  function alterationOf(item) {
    if (!item || !item.gfAI) return null;
    var j = item.gfAI.labelJob || (isAlteration(item.gfAI.job) ? item.gfAI.job : null);
    return j && isAlteration(j) ? j : null;
  }

  // Everything that was altered in the current video, as plain sentences.
  function summary(mediaList) {
    var seen = {};
    (mediaList || []).forEach(function (m) {
      var j = alterationOf(m);
      if (j) seen[j] = true;
    });
    var jobs = Object.keys(seen);
    if (!jobs.length) return null;
    return {
      jobs: jobs,
      lines: jobs.map(function (j) { return (ALTERATIONS[j] || ALTERATIONS.generic).why; }),
      remarks: remarksLine(),
      social: socialLine()
    };
  }

  /* -------------------------------------------------- exporting the paper trail */
  function exportRecord(address) {
    var rows = read();
    var out = [];
    out.push("GOLDFRAME — AI IMAGE DISCLOSURE RECORD");
    out.push("Generated " + new Date().toLocaleString());
    if (address) out.push("Property: " + address);
    out.push("");
    out.push("This record lists every image in this account that Goldframe altered with AI,");
    out.push("what was changed, and which model made the change. Unaltered originals are kept");
    out.push("inside each Goldframe project and can be exported with Projects ▸ Export.");
    out.push("");
    out.push("California AB 723 (effective 1 Jan 2026) requires that materially altered listing");
    out.push("images be labelled and that the unaltered original be reachable. Brightness,");
    out.push("contrast, white balance and cropping are enhancements and are not listed here.");
    out.push("");
    if (!rows.length) out.push("(No AI alterations recorded.)");
    rows.forEach(function (r, i) {
      out.push((i + 1) + ". " + new Date(r.at).toLocaleString());
      out.push("   Photo:  " + (r.photo || "(unnamed)"));
      out.push("   Change: " + r.job + "  —  labelled \"" + r.label + "\"");
      out.push("   Model:  " + r.model);
      if (r.prompt) out.push("   Asked:  " + r.prompt);
      if (r.address) out.push("   Listing:" + r.address);
      out.push("");
    });
    out.push("--");
    out.push(remarksLine());
    return out.join("\n");
  }

  window.GFCompliance = {
    isAlteration: isAlteration,
    alterationOf: alterationOf,
    labelFor: labelFor,
    watermark: watermark,
    log: log,
    read: read,
    clear: clear,
    remarksLine: remarksLine,
    socialLine: socialLine,
    summary: summary,
    exportRecord: exportRecord,
    ALTERATIONS: ALTERATIONS
  };
})();
